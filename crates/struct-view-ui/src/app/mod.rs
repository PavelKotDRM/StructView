//! # Модуль приложения StructView
//!
//! Содержит структуру [`StructViewApp`] — основное состояние приложения —
//! и реализацию трейта [`eframe::App`], управляющего жизненным циклом GUI.
//!
//! ## Архитектура UI
//!
//! ```text
//! ┌──────────────────────────────────────────────┐
//! │  Top Panel: меню + строка поиска             │
//! ├──────────────────────────────────────────────┤
//! │  Central Panel: активная визуализация        │
//! ├──────────────────────────────────────────────┤
//! │  Bottom Panel (Status Bar): имя/размер файла │
//! └──────────────────────────────────────────────┘
//! ```
//!
//! ## Состав подмодулей
//!
//! | Подмодуль | Назначение |
//! |-----------|-----------|
//! | `state` | Структура [`StructViewApp`] и типы состояния |
//! | `state/` | Загрузка, сохранение, история, операции документа и диалог редактирования |
//! | `i18n/` | Локаль, ключи сообщений и раздельные каталоги переводов |
//! | `panels/` | Верхняя панель, статус-бар и центральная область |
//! | `tree/` | Модели строк, виртуализированный рендеринг и контекстные меню |
//! | `visualization/` | Модели таблицы, графа и схемы с отдельной логикой вывода схем |
//! | `views/` | Отрисовка таблицы, графа, схемы и сравнений |
//! | `edit/` | Правка полей, работа с путями и операции над структурами |
//! | `theme` | Цветовая схема подсветки синтаксиса и совпадений поиска |

mod edit;
mod i18n;
mod panels;
mod state;
mod theme;
mod tree;
mod views;
mod visualization;

