//! # Модуль приложения StructView
//!
//! Содержит структуру [`StructViewApp`] — основное состояние приложения —
//! и реализацию трейта [`eframe::App`], управляющего жизненным циклом GUI.
//!
//! ## Архитектура UI
//!
//! ```text
//! ┌──────────────────────────────────────────────┐
//! │  Top Panel: меню + строка поиска             │
//! ├──────────────────────────────────────────────┤
//! │  Central Panel: активная визуализация          │
//! ├──────────────────────────────────────────────┤
//! │  Bottom Panel (Status Bar): имя/размер файла │
//! └──────────────────────────────────────────────┘
//! ```
//!
//! ## Состав подмодулей
//!
//! | Подмодуль | Назначение |
//! |-----------|-----------|
//! | `state` | Структура [`StructViewApp`], загрузка/сохранение файлов, тема, уведомления |
//! | `i18n` | Языки интерфейса и каталог переводов |
//! | `panels` | Отрисовка верхней, нижней и центральной панелей |
//! | `tree` | Рекурсивная отрисовка дерева JSON и контекстное меню узла |
//! | `visualization` | Построение табличной, графовой и схемной моделей |
//! | `views` | Отрисовка таблицы, графа, схемы и парного diff |
//! | `edit` | Конструктор значений, правка узлов и обратное преобразование дерева в [`serde_json::Value`] |
//! | `theme` | Цветовая схема подсветки синтаксиса и совпадений поиска |

