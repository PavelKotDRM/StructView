//! # JSON Viewer — библиотека
//!
//! Быстрое, кроссплатформенное десктопное приложение для чтения и навигации
//! по JSON-файлам.
//!
//! ## Архитектура
//!
//! ```text
//! ┌──────────────────────────────────────────────┐
//! │  Top Panel: меню + строка поиска             │
//! ├──────────────────────────────────────────────┤
//! │  Central Panel: ScrollArea + дерево JSON     │
//! ├──────────────────────────────────────────────┤
//! │  Bottom Panel (Status Bar): имя/размер файла │
//! └──────────────────────────────────────────────┘
//! ```
//!
//! | Модуль | Назначение |
//! |--------|-----------|
//! | [`app`] | Главное состояние приложения, реализация [`eframe::App`], вся логика UI |
//! | [`parser`] | Парсинг JSON-строки в дерево [`parser::JsonNode`]; обнаружение ошибок |
//! | [`search`] | Полнотекстовый поиск по узлам дерева, навигация Next/Prev |
//! | [`clipboard`] | Копирование текста в системный буфер обмена через `arboard` |

#![deny(warnings)]

pub mod app;
pub mod clipboard;
pub mod parser;
pub mod search;
